from russian_coordinates import PAGES as COORDINATES
from russian_fundamentals import PAGES as FUNDAMENTALS, section

PAGES = {}


def add(path, title, label, intro, *sections):
    PAGES[path] = dict(title=f'{title} — Школа Кода', heading=title, eyebrow=label,
                       intro=intro, sections=list(sections))


def links(*paths):
    sources = {**COORDINATES, **FUNDAMENTALS, **PAGES}
    return [[path, sources[path]['heading'], sources[path]['intro']] for path in paths]


def project(slug, title, label, intro, setup, steps, tests, next_idea):
    add('/projects/' + slug, title, label, intro,
        section('Подготовка', 'Что понадобится', paragraphs=[setup]),
        section('Порядок работы', 'От замысла к проверке', items=steps),
        section('Проверки', 'Что может пойти иначе?', items=tests),
        section('Демонстрация', 'Покажи решение и объясни выбор', paragraphs=[next_idea]))


