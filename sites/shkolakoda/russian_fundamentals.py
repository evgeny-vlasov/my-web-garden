def unit(topic_slug, lesson_slug, topic_title, lesson_title, overview,
         concepts, warnings, timeline, activity, checkpoints, extension, projects):
    topic = '/topics/' + topic_slug
    lesson = '/lessons/' + lesson_slug
    paths = ['/projects/' + slug for slug in projects]
    page(topic, topic_title, 'Тема / Scratch и робототехника', overview, [
        section('Основные понятия', 'Что происходит в программе', cards=concepts),
        section('Попробуй', 'Проверь правило на маленьком примере', paragraphs=[activity]),
        section('Отладка', 'На что смотреть, если результат неожиданный', items=warnings),
    ])
    page(lesson, lesson_title, 'Занятие / Scratch / 90 минут', overview, [
        section('План занятия', 'От идеи к работающему проекту', timeline=timeline),
        section('Практика', 'Сначала предскажи результат', paragraphs=[activity]),
        section('Проверки преподавателя', 'Что ученик сможет показать', items=checkpoints),
        section('Усложнение', 'Измени правило и объясни результат', paragraphs=[extension]),
        section('Родителям', 'Вопрос после демонстрации',
                paragraphs=['Попросите ребёнка показать одну проверку, в которой результат его удивил. Что он изменил и как убедился, что теперь правило работает?']),
    ])
    for path in [topic, lesson, *paths]:
        if path not in PAGES:
            continue
        page_data = PAGES[path]
        if path in (topic, lesson):
            page_data['breadcrumbs'] = [card_link(topic)[:2], card_link(lesson)[:2]]
        page_data['sections'].append(section(
            'Учебный маршрут', 'Продолжить работу',
            links=[card_link(destination) for destination in [topic, lesson, *paths]
                   if destination != path],
        ))


