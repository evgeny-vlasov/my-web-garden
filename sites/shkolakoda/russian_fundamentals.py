from russian_coordinates import PIGEON, TAXI, TOPIC as COORDINATES

PAGES = {}

COORDINATE_LINKS = {
    COORDINATES: ['Координаты и движение', 'Прочитай положение и предскажи следующий шаг.'],
    PIGEON: ['Побег от гигантского голубя', 'Выбери исход при одновременных касаниях.'],
    TAXI: ['Бабушкино межгалактическое такси', 'Раздели посадку и доставку на два состояния.'],
}


def section(label, heading, **content):
    return {'eyebrow': label, 'heading': heading, **content}


def card_link(path):
    if path in COORDINATE_LINKS:
        return [path, *COORDINATE_LINKS[path]]
    page = PAGES[path]
    return [path, page['heading'], page['intro']]


def page(path, title, label, intro, sections):
    PAGES[path] = {
        'title': f'{title} — Школа Кода', 'heading': title, 'eyebrow': label,
        'intro': intro, 'sections': sections, 'learning_path': True,
    }


def project(slug, title, duration, intro, needs, steps, checks, challenges, parent):
    page('/projects/' + slug, title, f'Проект / {duration} мин', intro, [
        section('Подготовка', 'Что понадобится', paragraphs=[needs]),
        section('Порядок сборки', 'Собирай по шагам', items=steps),
        section('Проверки', 'Попробуй и неудобные случаи', items=checks),
        section('Усложнения', 'Выбери одно изменение', items=challenges),
        section('Демонстрация', 'Покажи, почему это работает', paragraphs=[parent]),
    ])


